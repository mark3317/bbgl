inline bool Russian() {
    static const bool russian = [] {
        if (const char* ui = std::getenv("BB_UI_LANGUAGE"); ui && *ui)
            return std::strcmp(ui, "ru") == 0;
        const char* game = std::getenv("BB_LANGUAGE");
        return game && std::strcmp(game, "8") == 0;
    }();
    return russian;
}
