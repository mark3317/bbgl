"""Pack the approved ImageGen artwork as embedded SDL RGBA cursor surfaces.

Only asset conversion (alpha bounds, UI sizing and byte packing); no painting.
Run from any directory with Pillow installed. No runtime image dependency.
"""
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "assets/cursors/silver-arrow.png"
TARGET = ROOT / "gpu/shim/silver_cursor_data.h"


def main():
    source = Image.open(SOURCE).convert("RGBA")
    bounds = source.getchannel("A").point(lambda a: 255 if a >= 64 else 0).getbbox()
    if not bounds:
        raise ValueError("Cursor artwork is empty")
    source = source.crop(bounds)
    parts = ["// Generated by tools/build_silver_cursor.py; do not hand-edit.\n"
             "#pragma once\nnamespace BbSilverCursor {\n"]
    for factor in (1, 2):
        size = (32 * factor, 48 * factor)
        art = source.copy()
        art.thumbnail((30 * factor, 46 * factor), Image.Resampling.LANCZOS)
        canvas = Image.new("RGBA", size)
        canvas.paste(art, (factor, factor))
        if factor == 1:
            alpha = canvas.getchannel("A")
            tip_y = next(y for y in range(size[1]) if alpha.crop((0,y,size[0],y+1)).getextrema()[1] >= 128)
            tip_x = next(x for x in range(size[0]) if alpha.getpixel((x,tip_y)) >= 128)
            parts.append(f"inline constexpr int Width=32, Height=48, HotX={tip_x}, HotY={tip_y};\n")
            canvas.save(SOURCE.with_name("silver-arrow-32x48.png"))
        raw = canvas.tobytes()
        parts.append(f"inline constexpr unsigned char Pixels{factor}x[] = {{\n")
        parts.extend("    " + ",".join(str(v) for v in raw[i:i+32]) + ",\n" for i in range(0,len(raw),32))
        parts.append("};\n")
    parts.append("} // namespace BbSilverCursor\n")
    TARGET.write_text("".join(parts), encoding="utf-8")
    print(f"Packed silver arrow, hotspot ({tip_x},{tip_y}), 32x48 + 64x96")


if __name__ == "__main__":
    main()
